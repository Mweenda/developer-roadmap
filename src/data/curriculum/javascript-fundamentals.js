function concept({ id, title, minutes, summary, definition, why, model, syntax, language = 'js', examples, mistakes, use, docs }) {
  return {
    id,
    title,
    minutes,
    summary,
    content: [
      { type: 'h', text: 'Definition' },
      { type: 'p', text: definition },
      { type: 'h', text: 'Why it matters' },
      { type: 'p', text: why },
      { type: 'h', text: 'Mental model' },
      { type: 'note', text: model },
      { type: 'h', text: 'Syntax' },
      { type: 'code', language, code: syntax },
      { type: 'h', text: 'Examples' },
      { type: 'code', language, code: examples },
      { type: 'h', text: 'Common mistakes' },
      { type: 'ul', items: mistakes },
      { type: 'h', text: 'Real-world use' },
      { type: 'p', text: use },
      { type: 'note', text: `Look it up: ${docs}` },
    ],
  };
}

